    public String generarCodigoAleatorio() {
    String caracteres = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
    StringBuilder codigo = new StringBuilder();
    Random rnd = new Random();
    while (codigo.length() < 6) { 
        int index = (int) (rnd.nextFloat() * caracteres.length());
        codigo.append(caracteres.charAt(index));
    }
    return codigo.toString();
}
    
     public String verificarYGuardarCodigo(String nombre, String apellidoPaterno, String apellidoMaterno) throws SQLException {
        String codigo_Generado = generarCodigoAleatorio();
        try (Connection conn = DriverManager.getConnection("jdbc:postgresql://localhost:5432/Zsys", "postgres", "7568")) {
            String sql = "UPDATE guardia SET codigo_recup = ? WHERE nombres = ? AND apellido_paterno = ? AND apellido_materno = ?";
            PreparedStatement pstmt = conn.prepareStatement(sql);
            pstmt.setString(1, codigo_Generado);
            pstmt.setString(2, nombre);
            pstmt.setString(3, apellidoPaterno);
            pstmt.setString(4, apellidoMaterno);
            int rowsAffected = pstmt.executeUpdate();
            if (rowsAffected > 0) {
                return codigo_Generado;
            } else {
                return null;
            }
        }
    }
  
