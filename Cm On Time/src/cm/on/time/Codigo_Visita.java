    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
 String id_Visita = jTextField1.getText();

    if (id_Visita.isEmpty()) {
        JOptionPane.showMessageDialog(this, "El código de visita debe ser ingresado.");
        return;
    }

    JOptionPane.showMessageDialog(this, "El visitante ya puede salir.");

    try {
       ConexionBD conexionBD = new ConexionBD();
       Connection conn = null;
        conn = conexionBD.Conectar();
        String sql = "DELETE FROM visita_temporal WHERE id_visita = ?";
        PreparedStatement pstmt = conn.prepareStatement(sql);
        pstmt.setString(1, id_Visita);
        int rowsAffected = pstmt.executeUpdate();
        pstmt.close();
        conn.close();

        if (rowsAffected > 0) {
            System.out.println("Datos eliminados exitosamente.");
        } else {
            JOptionPane.showMessageDialog(this, "No se encontró el código de visita.");
        }
        
        this.dispose();
    
     java.awt.EventQueue.invokeLater(() ->{
        new Ingreso_Manual_Visitante().setVisible(true);
    });

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al eliminar los datos.");
    }
      }//GEN-LAST:event_jButton1ActionPerformed

