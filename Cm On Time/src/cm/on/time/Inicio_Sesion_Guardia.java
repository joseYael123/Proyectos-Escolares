    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String nombres = jTextField1.getText().trim();
        String id_guardia = new String(jPasswordField1.getPassword()).trim();
        String hora_entrada = jTextField2.getText().trim();
        
        System.out.println("Nombre: " + nombres);
        System.out.println("ID Guardia: " + id_guardia);
        System.out.println("Hora Entrada: " + hora_entrada);

        
        if(nombres.isEmpty() || id_guardia.isEmpty() || hora_entrada.isEmpty()){
            JOptionPane.showMessageDialog(null, "Por favor llene todos los campos.");
           return; 
        }
    
    ConexionBD conexionBD =new ConexionBD();
    Connection conexion = conexionBD.Conectar();
    
    if(conexion != null){
        Autenticacion_Guardia autenticacion = new Autenticacion_Guardia();
       autenticacion.autenticar_guard(conexion, nombres, id_guardia, hora_entrada);
        
        if(autenticacion != null) {
            JOptionPane.showMessageDialog(null, "¡Bienvenido a Zsys!");
            
            this.dispose();
            
            java.awt.EventQueue.invokeLater(() -> {
                new Interfaz_Principal_Guardia().setVisible(true);
            });
          } else {
            JOptionPane.showMessageDialog(null, "Datos Incorrectos. Vuelva a Ingresarlos Por favor");
        }
         if (conexion != null) {
        try {
            conexion.close();
            System.out.println("Desconexion Exitosa");
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al cerrar la conexión a la base de datos.", "Error", JOptionPane.ERROR_MESSAGE);
        }
      }
    }
    }//GEN-LAST:event_jButton2ActionPerformed

