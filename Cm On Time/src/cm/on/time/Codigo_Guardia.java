    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
   String codigoIngresado = jTextField1.getText();

        if (codigoIngresado.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese el código generado.");
            return;
        }

        String idGuardia = null;
        try {
            idGuardia = obtenerIdGuardiaPorCodigo(codigoIngresado);
        } catch (SQLException ex) {
            Logger.getLogger(Codigo_Guardia.class.getName()).log(Level.SEVERE, null, ex);
        }
        if (idGuardia != null) {
            JOptionPane.showMessageDialog(this, "ID del Guardia: " + idGuardia);
        } else {
            JOptionPane.showMessageDialog(this, "Código no encontrado.");
        }
      }//GEN-LAST:event_jButton1ActionPerformed

