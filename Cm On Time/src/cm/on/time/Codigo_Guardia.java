     public String obtenerIdGuardiaPorCodigo(String codigo) throws SQLException {
        String idGuardia = null;
        try (Connection conn = DriverManager.getConnection("jdbc:postgresql://localhost:5432/Zsys", "postgres", "7568")) {
            String sql = "SELECT id_guardia FROM guardia WHERE codigo_recup = ?";
            PreparedStatement pstmt = conn.prepareStatement(sql);
            pstmt.setString(1, codigo);
            ResultSet rs = pstmt.executeQuery();
            if (rs.next()) {
                idGuardia = rs.getString("id_guardia");
            }
        }
        return idGuardia;
    }

