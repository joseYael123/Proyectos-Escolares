    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String nombre_esp = jTextField1.getText().trim();
        String contraseña = new String(jPasswordField1.getPassword()).trim();
        
        if(nombre_esp.isEmpty() || contraseña.isEmpty()){
            JOptionPane.showMessageDialog(null, "Por favor llene todos los campos.");
           return; 
        }
    
       System.out.println("Usuario:" + nombre_esp);
       System.out.println("Contraseña:" + contraseña);
       
    ConexionBD conexionBD =new ConexionBD();
    Connection conexion = conexionBD.Conectar();
    
    if(conexion != null){
        Autenticacion_Administrador autenticacion = new Autenticacion_Administrador();
        boolean autenticado = autenticacion.autenticar_admin(conexion,nombre_esp,contraseña);
        
        if(autenticado) {
            JOptionPane.showMessageDialog(null, "¡Bienvenido a Zsys!");
            
            this.dispose();
            
            java.awt.EventQueue.invokeLater(() -> {
                new Interfaz_Principal_Administrador().setVisible(true);
            });
          } else {
            JOptionPane.showMessageDialog(null, "Datos Incorrectos. Vuelva a Ingresarlos Por favor");
        }
          if (conexion != null) {
        try {
            conexion.close();
            System.out.println("Desconexion Exitosa");
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al cerrar la conexión a la base de datos.", "Error", JOptionPane.ERROR_MESSAGE);
        }
      }
    }
    }//GEN-LAST:event_jButton2ActionPerformed

